#!/usr/bin/env python3
"""Generate the factory-config embed (src/factory_config.h, g_factory_embed) for an IDF build.

Run by main/CMakeLists.txt at configure time when OD_FACTORY_CONFIG_HEX (or the environment
variable OPENDISPLAY_FACTORY_CONFIG_HEX) is set. The packet is validated with the same rules
as the Toolbox upload (length field, outer CRC, 4096 B ceiling) so a bad packet fails the
configure instead of shipping an image whose embed the firmware would silently ignore.

usage: factory_config_embed.py --out <file.cpp> --hex "<config packet hex>"
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config_packet import MAX_PACKET, parse_hex_bytes, validate_packet  # noqa: E402

MAGIC = 0xFAC70A5A


def render(packet: bytes) -> str:
    padded = packet + b"\x00" * (MAX_PACKET - len(packet))
    rows = []
    for i in range(0, len(padded), 16):
        rows.append("        " + ", ".join(f"0x{b:02X}" for b in padded[i:i + 16]) + ",")
    body = "\n".join(rows)
    return (
        "// Generated by tools/factory_config_embed.py at configure time. Do not edit.\n"
        '#include "factory_config.h"\n'
        "\n"
        "const factory_flash_cfg_t g_factory_embed = {\n"
        f"    0x{MAGIC:08X}u,\n"
        f"    {len(packet)}u,\n"
        "    {\n"
        f"{body}\n"
        "    }\n"
        "};\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--hex", required=True)
    args = ap.parse_args()
    try:
        packet = parse_hex_bytes(args.hex)
        validate_packet(packet)
    except ValueError as exc:
        print(f"factory_config_embed: {exc}", file=sys.stderr)
        return 1
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = render(packet)
    # Unchanged content keeps its mtime, so a reconfigure does not force a rebuild.
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")
    print(f"factory_config_embed: embedded {len(packet)} byte config packet")
    return 0


if __name__ == "__main__":
    sys.exit(main())
