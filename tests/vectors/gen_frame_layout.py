#!/usr/bin/env python3
"""Write tests/vectors/frame_layout.inc: frames packed by py-opendisplay's frame layout packer
(opendisplay.encoding.layout.lay_out_plane), for tests/host/color_test.c to compare the firmware
frame walker against byte for byte.

    <py-opendisplay venv>/bin/python tests/vectors/gen_frame_layout.py

Every case packs the raster code(x, y, plane) below; color_test.c computes the same raster.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from opendisplay.encoding.layout import lay_out_plane
from opendisplay.models.frame_layout import FrameLayout

OUT = Path(__file__).resolve().parent / "frame_layout.inc"

# (label, scheme, bits, planes, width, height, white, layout)
CASES = [
    ("linear BWRY", 3, 2, 1, 13, 5, 1, {}),
    ("GDEY0579F52 shape: split + FOLD", 3, 2, 1, 32, 6, 1, {"frame_split": 1, "row_order": 1}),
    ("FOLD odd height", 3, 2, 1, 8, 7, 1, {"row_order": 1}),
    ("CrowPanel shape: split 16/8 column-major", 0, 1, 1, 24, 5, 1,
     {"frame_split": 1, "frame_scan": 1, "part_width": 16, "part_stride": 8}),
    ("split 16/8, right part past the edge", 0, 1, 1, 20, 4, 1,
     {"frame_split": 1, "part_width": 16, "part_stride": 8}),
    ("mirror X + Y", 3, 2, 1, 12, 4, 1, {"frame_scan": 6}),
    ("split + mirror X", 4, 4, 1, 16, 3, 1, {"frame_split": 1, "frame_scan": 2}),
    ("LSB first", 0, 1, 1, 20, 3, 1, {"frame_scan": 8}),
    ("column-major + mirror Y", 0, 1, 1, 16, 5, 1, {"frame_scan": 5}),
    ("NIBBLE", 3, 2, 1, 10, 3, 1, {"pixel_pack": 1}),
    ("INTERLEAVE", 3, 2, 1, 12, 4, 1, {"row_order": 2}),
    ("INTERLEAVE + mirror Y", 3, 2, 1, 8, 6, 1, {"row_order": 2, "frame_scan": 4}),
    ("invert, one plane", 0, 1, 1, 13, 3, 1, {"plane_invert": 1}),
    ("BWR plane 1 inverted", 1, 1, 2, 16, 3, 0, {"plane_invert": 2}),
    ("split BWGBRY (the former scheme 8)", 4, 4, 1, 16, 4, 1, {"frame_split": 1}),
]


def code(x: int, y: int, plane: int, bits: int) -> int:
    return ((x * 7 + y * 13 + plane * 5) ^ (x >> 2)) & ((1 << bits) - 1)


def main() -> int:
    out = ["/* GENERATED by tests/vectors/gen_frame_layout.py from py-opendisplay's",
           " * opendisplay.encoding.layout.lay_out_plane -- do not edit. */",
           "typedef struct {",
           "    const char *label;",
           "    uint8_t scheme, bits, plane, white;",
           "    uint16_t width, height;",
           "    uint8_t frame_split, frame_scan, plane_invert, pixel_pack, row_order;",
           "    uint16_t part_width, part_stride;",
           "    const uint8_t *bytes;",
           "    uint32_t n;",
           "} fl_case_t;", ""]
    rows = []
    for i, (label, scheme, bits, planes, w, h, white, lay) in enumerate(CASES):
        layout = FrameLayout.from_mapping(lay)
        for plane in range(planes):
            codes = np.array([[code(x, y, plane, bits) for x in range(w)] for y in range(h)],
                             dtype=np.uint8)
            b = lay_out_plane(codes, bits, layout, white=white, plane=plane, planes=planes)
            name = f"k_fl_{i}_{plane}"
            out.append(f"static const uint8_t {name}[{len(b)}] = {{")
            for o in range(0, len(b), 16):
                out.append("    " + ", ".join(f"0x{v:02X}" for v in b[o:o + 16]) + ",")
            out.append("};")
            rows.append(f'    {{ "{label} (plane {plane})", {scheme}u, {bits}u, {plane}u, {white}u, '
                        f'{w}u, {h}u, {lay.get("frame_split", 0)}u, {lay.get("frame_scan", 0)}u, '
                        f'{lay.get("plane_invert", 0)}u, {lay.get("pixel_pack", 0)}u, '
                        f'{lay.get("row_order", 0)}u, {lay.get("part_width", 0)}u, '
                        f'{lay.get("part_stride", 0)}u, {name}, {len(b)}u }},')
    out += ["", "static const fl_case_t k_fl_cases[] = {"] + rows + ["};", ""]
    OUT.write_text("\n".join(out))
    print(f"{len(rows)} cases -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
