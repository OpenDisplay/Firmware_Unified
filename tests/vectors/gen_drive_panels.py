#!/usr/bin/env python3
"""Emit tests/vectors/drive_panels.inc from the panel database (panels/generated/drive_presets.json).

A representative slice of the 77 panel ids -- one per controller family, colour class and escape
the executor implements -- copied verbatim so the host suites drive od_cfg_index / od_epd_cfg /
od_epd with exactly the packet bodies a device receives. The golden traces in
tests/vectors/epd_golden/ are recorded from these.

Stdlib only; not run by the gate:

    python3 -I tests/vectors/gen_drive_panels.py <drive_presets.json> <source-sha> \
        > tests/vectors/drive_panels.inc
"""
import json
import re
import sys

# id -> why it is in the set
REPRESENTATIVE = [
    ("0x0001", "UC81xx mono, full only"),
    ("0x0002", "SSD16xx mono, full + fast + partial"),
    ("0x0014", "UC81xx 7.5in mono, large frame"),
    ("0x001E", "UC81xx BWRY 2.9in, colour16 3-pass with LUT slots (ODBEEBA6 glass)"),
    ("0x0024", "UC81xx BWR two controller planes"),
    ("0x0028", "SSD16xx 4-grey"),
    ("0x0033", "SSD16xx 7.9in, SET_PIN"),
    ("0x0023", "UC81xx Spectra 6"),
    ("0x0034", "UC81xx BWRY 2.13in, full + fast"),
    ("0x0040", "UC81xx BWRY 7.5in, colour16 (LUT after full init)"),
]


def ident(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def main():
    db = json.load(open(sys.argv[1]))
    sha = sys.argv[2] if len(sys.argv) > 2 else "unknown"
    out = [
        "/* GENERATED by tests/vectors/gen_drive_panels.py -- do not edit.",
        " * Source: Firmware_Unified v3/panel-data %s, panels/generated/drive_presets.json." % sha,
        " * Each packet is a BODY (instance byte first), as stored after the 4-byte",
        " * [number][id][len:2] header of the length-prefixed range. */",
    ]
    rows = []
    for pid, why in REPRESENTATIVE:
        p = db["panels"][pid]
        name = ident(p["name"]) + "_" + pid[2:].lower()
        out.append("/* %s %s: %s */" % (pid, p["name"], why))
        entries = []
        for i, pkt in enumerate(p["packets"]):
            raw = bytes.fromhex(pkt["body_hex"])
            var = "fxp_%s_%d" % (name, i)
            out.append("static const uint8_t %s[%d] = { %s };"
                       % (var, len(raw), ", ".join("0x%02x" % b for b in raw)))
            entries.append((pkt["id"], var, len(raw)))
        out.append("static const fx_panel_pkt_t fxp_%s[] = {" % name)
        for i, var, n in entries:
            out.append("    { 0x%02X, %s, %d }," % (i, var, n))
        out.append("};")
        rows.append((p["name"] + "_" + pid, p["width"], p["height"], p["color_scheme"], name,
                     len(entries)))
    out.append("static const fx_panel_t FX_PANELS[] = {")
    for label, w, h, scheme, name, n in rows:
        out.append('    { "%s", %d, %d, %d, fxp_%s, %d },' % (label, w, h, scheme, name, n))
    out.append("};")
    out.append("#define FX_PANEL_COUNT %d" % len(rows))
    print("\n".join(out))


if __name__ == "__main__":
    main()
