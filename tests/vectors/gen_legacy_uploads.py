#!/usr/bin/env python3
"""Emit tests/vectors/legacy_uploads.inc: what a 2.x client sends to upload an image, for one
panel of every colour class in the panel database.

The frames are built by py-opendisplay 7.14.0 -- the last client that knows nothing about drive
modes -- exactly as its upload path does: the pixel format from DisplayConfig 0x20 (panel_ic_type
+ color_scheme, including the per-panel BWRY / 4-grey code tables), zlib with the firmware's
9-bit window, CMD 0x70 START (compressed or not), 0x71 DATA in CHUNK_SIZE pieces, 0x72 END; and
for one panel the PIPE flow (0x80 / 0x81, auto-completing). tests/host/legacy_upload_test.c replays them
through od_xfer / od_pipe into od_display and checks they render through mode 0.

The image is a deterministic palette pattern rather than a dithered photo: what is under test is
the frame layout, not the dither.

Not run by the gate (it needs py-opendisplay); regenerate with

    UV_OFFLINE=1 uv run --no-project --python 3.13 --with py-opendisplay==7.14.0 \\
        python -I tests/vectors/gen_legacy_uploads.py panels/generated/drive_presets.json \\
        > tests/vectors/legacy_uploads.inc
"""
import json
import sys
import zlib

import numpy as np
from PIL import Image

from opendisplay.display_palettes import get_bwry_codes, get_gray4_codes
from opendisplay.encoding.bitplanes import encode_bitplanes, encode_gray4_bitplanes
from opendisplay.encoding.compression import compress_image_data
from opendisplay.encoding.images import encode_2bpp, encode_image
from opendisplay.protocol import commands as C
from epaper_dithering import ColorScheme

PY_OD_VERSION = "7.14.0"
WINDOW_BITS = 9  # FIRMWARE_ZLIB_WINDOW_BITS in py-opendisplay's device.py

# (panel id, colours in the scheme, uncompressed flow too?, PIPE flow too?)
PANELS = [
    ("0x000A", 2, True, True),     # MONO 80x128
    ("0x000E", 3, True, False),    # BWR 152x152, two controller planes
    ("0x0034", 4, False, False),   # BWRY 122x250, panel code table
    ("0x0031", 4, False, False),   # GRAY4 122x250, two 1-bit planes
    ("0x004A", 6, False, False),   # BWGBRY (Spectra 6) 400x600, 4 bpp
    ("0x002B", 6, False, False),   # BWGBRY_SPLIT 1024x576, two halves on two CS
]


def pattern(w, h, n):
    y, x = np.mgrid[0:h, 0:w]
    idx = (((x // 8) ^ (y // 4)) * 7 + (y // 16)) % n
    img = Image.fromarray(idx.astype(np.uint8), mode="P")
    img.putpalette([v for i in range(n) for v in (i * 40, i * 40, i * 40)])
    return img


def encode(ic, scheme, img):
    """device.py _prepare_image's encode step, verbatim in behaviour."""
    cs = next(c for c in ColorScheme if c.value == scheme)
    if cs in (ColorScheme.BWR, ColorScheme.BWY):
        p1, p2 = encode_bitplanes(img, cs)
        return p1 + p2
    if cs == ColorScheme.GRAYSCALE_4:
        return b"".join(encode_gray4_bitplanes(img, get_gray4_codes(ic)))
    if cs == ColorScheme.BWRY:
        return encode_2bpp(img, codes=get_bwry_codes(ic))
    return encode_image(img, cs)


def direct_flow(data, compressed):
    frames = []
    if compressed:
        comp = compress_image_data(data, level=6, window_bits=WINDOW_BITS)
        start, rest = C.build_direct_write_start_compressed(len(data), comp,
                                                            max_start_payload=C.MAX_START_PAYLOAD)
        frames.append(start)
        payload = rest
    else:
        frames.append(C.build_direct_write_start_uncompressed())
        payload = data
    for off in range(0, len(payload), C.CHUNK_SIZE):
        frames.append(C.build_direct_write_data_command(payload[off:off + C.CHUNK_SIZE]))
    frames.append(C.build_direct_write_end_command(0))
    return frames


def pipe_flow(data):
    """Uncompressed PIPE, window 1 / ack every 1, 244-byte frames, no END."""
    max_frame = 244
    frames = [C.build_pipe_write_start_command(False, 1, 1, max_frame, len(data))]
    step = max_frame - C.PIPE_FRAME_OVERHEAD
    for seq, off in enumerate(range(0, len(data), step)):
        frames.append(C.build_pipe_write_data_command(seq & 0xFF, data[off:off + step]))
    # An uncompressed full-frame PIPE transfer auto-completes on its last byte; py-opendisplay
    # sends no END then (device.py _run_pipe_upload).
    return frames


def c_bytes(name, frames, prefixed=True):
    blob = b"".join((len(f).to_bytes(2, "little") if prefixed else b"") + f for f in frames)
    rows = [", ".join("0x%02x" % b for b in blob[i:i + 20]) for i in range(0, len(blob), 20)]
    return ["static const uint8_t %s[%d] = {" % (name, len(blob))] + \
           ["    %s," % r for r in rows] + ["};"]


def main():
    db = json.load(open(sys.argv[1]))
    out = [
        "/* GENERATED by tests/vectors/gen_legacy_uploads.py with py-opendisplay %s -- do not edit."
        % PY_OD_VERSION,
        " * Each stream is a run of [len:2 LE][frame], a frame being [opcode:2 BE][body] as the",
        " * client writes it. drive[] is the panel database's default-class packets, framed. */",
    ]
    rows = []
    for pid, n, raw, pipe in PANELS:
        e = db["panels"][pid]
        ic, w, h, scheme = e["panel_ic_type"], e["width"], e["height"], e["color_scheme"]
        data = encode(ic, scheme, pattern(w, h, n))
        tag = "lu_%s" % pid[2:].lower()
        out.append("/* %s %s, color_scheme %d, %d B frame */" % (pid, e["name"], scheme, len(data)))
        out += c_bytes(tag + "_drive", [bytes.fromhex(e["targets"]["default"]["framed_hex"])],
                   prefixed=False)
        out += c_bytes(tag + "_z", direct_flow(data, True))
        out += c_bytes(tag + "_raw", direct_flow(data, False)) if raw else []
        out += c_bytes(tag + "_pipe", pipe_flow(data)) if pipe else []
        rows.append("    { \"%s %s\", 0x%04X, %d, %d, %d, %du, 0x%08Xu, %s_drive, sizeof %s_drive, "
                    "%s_z, sizeof %s_z, %s, %s, %s, %s },"
                    % (pid, e["name"], ic, w, h, scheme, len(data), zlib.crc32(data), tag, tag,
                       tag, tag,
                       tag + "_raw" if raw else "NULL", "sizeof " + tag + "_raw" if raw else "0",
                       tag + "_pipe" if pipe else "NULL", "sizeof " + tag + "_pipe" if pipe else "0"))
    out.append("static const lu_panel_t LU_PANELS[] = {")
    out += rows
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
