#!/usr/bin/env python3
"""Regenerate tests/host/lut_vectors.inc from panels/waves/*.bin.

Each waveform is emitted raw and as raw deflate (wbits -10, the 0xAF compressed-slot format) in
three encodings: dynamic Huffman (level 9), fixed Huffman (Z_FIXED) and stored (level 0), so the
device inflater is checked against every block type zlib produces.

    python3 tests/host/gen_lut_vectors.py          # rewrite
    python3 tests/host/gen_lut_vectors.py --check  # exit 1 when the committed file is stale
"""
from __future__ import annotations

import sys
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
WAVES = REPO / "panels" / "waves"
OUT = REPO / "tests" / "host" / "lut_vectors.inc"

FAMILY = {800: 1, 535: 2}  # OD_LUT_FAMILY_S6_800, OD_LUT_FAMILY_JD_BWRY


def deflate(data: bytes, level: int, strategy: int = zlib.Z_DEFAULT_STRATEGY) -> bytes:
    c = zlib.compressobj(level, zlib.DEFLATED, -10, 9, strategy)
    return c.compress(data) + c.flush()


def arr(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def render() -> str:
    parts = ["/* Generated by tests/host/gen_lut_vectors.py from panels/waves. Do not edit. */", ""]
    rows = []
    for i, f in enumerate(sorted(WAVES.glob("*.bin"))):
        raw = f.read_bytes()
        encs = {
            "dyn": deflate(raw, 9),
            "fix": deflate(raw, 9, zlib.Z_FIXED),
            "sto": deflate(raw, 0),
        }
        for e in encs.values():
            assert zlib.decompress(e, -10) == raw
        parts.append(arr(f"k_raw_{i}", raw))
        for k, e in encs.items():
            parts.append(arr(f"k_{k}_{i}", e))
        rows.append(
            f'    {{ "{f.name}", {FAMILY.get(len(raw), 0)}u, k_raw_{i}, sizeof k_raw_{i}, '
            f"{{ k_dyn_{i}, k_fix_{i}, k_sto_{i} }}, "
            f"{{ sizeof k_dyn_{i}, sizeof k_fix_{i}, sizeof k_sto_{i} }} }},"
        )
    parts.append("")
    parts.append("typedef struct {\n    const char *name;\n    uint8_t family;\n"
                 "    const uint8_t *raw;\n    uint16_t raw_len;\n"
                 "    const uint8_t *z[3];\n    uint16_t z_len[3];\n} lut_vector_t;")
    parts.append("")
    parts.append("static const lut_vector_t k_lut_vectors[] = {")
    parts.extend(rows)
    parts.append("};")
    return "\n".join(parts) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
